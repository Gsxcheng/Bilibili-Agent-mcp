/**
 * Subtitle conversion. ASS output ported from Bilibili-Evolved
 * registry/lib/components/video/subtitle/subtitle-converter.ts (MIT); SRT / plain text added for AI use.
 */
import { normalizeAssContent, secondsToAssTime } from './danmaku/converter.js'

export interface SubtitleItem {
  from: number
  to: number
  location?: number
  content: string
}

export type SubtitleFormat = 'text' | 'srt' | 'ass' | 'json'

const srtTime = (seconds: number) => {
  const ms = Math.round(seconds * 1000)
  const h = Math.floor(ms / 3600000)
  const m = Math.floor((ms % 3600000) / 60000)
  const s = Math.floor((ms % 60000) / 1000)
  const rest = ms % 1000
  const pad = (n: number, l = 2) => String(n).padStart(l, '0')
  return `${pad(h)}:${pad(m)}:${pad(s)},${pad(rest, 3)}`
}

const clock = (seconds: number) => {
  const total = Math.floor(seconds)
  const h = Math.floor(total / 3600)
  const m = Math.floor((total % 3600) / 60)
  const s = total % 60
  const mm = String(m).padStart(2, '0')
  const ss = String(s).padStart(2, '0')
  return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`
}

export const toSrt = (items: SubtitleItem[]) =>
  items
    .map((it, i) => `${i + 1}\n${srtTime(it.from)} --> ${srtTime(it.to)}\n${it.content}\n`)
    .join('\n')

/** Compact transcript for LLM consumption: "[mm:ss] line" */
export const toText = (items: SubtitleItem[], withTimestamps = true) =>
  items
    .map(it => (withTimestamps ? `[${clock(it.from)}] ${it.content}` : it.content))
    .join('\n')

const LOCATIONS: Record<string, number> = {
  TopLeft: 7,
  TopCenter: 8,
  TopRight: 9,
  BottomLeft: 1,
  BottomCenter: 2,
  BottomRight: 3,
}

export const toAss = (
  items: SubtitleItem[],
  options: { title: string; width?: number; height?: number; size?: number; opacity?: number },
) => {
  const width = options.width ?? 1920
  const height = options.height ?? 1080
  const size = options.size ?? 3
  const opacity = options.opacity ?? 0.5
  const fontSize = ((10 * (size - 3) + 48) * height) / 720
  const color = '&H00FFFFFF'
  const background = `&H${Math.round(255 * (1 - opacity))
    .toString(16)
    .padStart(2, '0')
    .toUpperCase()}000000`
  const styles = Object.entries(LOCATIONS).map(
    ([name, value]) =>
      `Style: ${name},Microsoft YaHei,${fontSize},${color},${color},${background},${background},0,0,0,0,100,100,0,0,3,1,0,${value},32,32,32,0`,
  )
  const nameOf = (loc = 2) => Object.entries(LOCATIONS).find(([, v]) => v === loc)?.[0] ?? 'BottomCenter'
  const header = `[Script Info]
; Script generated by bilibili-agent-mcp (converter ported from Bilibili Evolved)
Title: ${options.title}
ScriptType: v4.00+
PlayResX: ${width}
PlayResY: ${height}
Timer: 10.0000
WrapStyle: 0
ScaledBorderAndShadow: no

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
${styles.join('\n')}

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text`
  const events = items.map(
    it =>
      `Dialogue: 0,${secondsToAssTime(it.from)},${secondsToAssTime(it.to)},${nameOf(it.location)},,0,0,0,,${normalizeAssContent(it.content)}`,
  )
  return `${header}\n${events.join('\n')}\n`
}
